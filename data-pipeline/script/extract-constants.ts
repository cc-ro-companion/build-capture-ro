// Writes constants.ts from an rAthena checkout. Run by hand when rAthena's
// script constants change:
//   node data-pipeline/script/extract-constants.ts [--rathena <dir>] && pnpm format
// The table is static because the parser tests run without rAthena.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { resolveRathenaDir } from '../rathena.ts';

/** Exported constant prefixes the parsed script subset can use (compared case-insensitively). */
const VALUE_PREFIXES = [
  'JOB_',
  'RC_',
  'RC2_',
  'ELE_',
  'SIZE_',
  'CLASS_',
  'EFF_',
  'BF_',
  'ATF_',
  'EAJ_',
  'EAJL_',
  'IG_',
];

/** Headers whose enums and #defines give the values of the exported constants. */
const HEADERS = [
  'src/common/mmo.hpp',
  'src/map/map.hpp',
  'src/map/mob.hpp',
  'src/map/status.hpp',
  'src/map/battle.hpp',
  'src/map/itemdb.hpp',
];

function stripComments(source: string): string {
  return source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

/** Evaluates a C constant expression of numbers, known names and | & + - << >> ~ ( ). */
function evaluate(expression: string, known: ReadonlyMap<string, number>): number | undefined {
  const tokens = expression.match(/0x[0-9a-fA-F]+|\d+|[A-Za-z_]\w*|<<|>>|[|&+\-~()]/g);
  if (tokens === null || tokens.join('') !== expression.replace(/\s+/g, '')) return undefined;
  const parts: string[] = [];
  for (const token of tokens) {
    if (/^[A-Za-z_]/.test(token)) {
      const value = known.get(token);
      if (value === undefined) return undefined;
      parts.push(`(${value})`);
    } else {
      parts.push(token.replace(/^(\d+)[uUlL]+$/, '$1'));
    }
  }
  // The input is restricted to numbers and operators by the token check above.
  return Number(new Function(`return (${parts.join(' ')});`)());
}

/** Resolves every `#define NAME value` and enum member in the headers to a number. */
function resolveHeaderValues(rathenaDir: string): Map<string, number> {
  const known = new Map<string, number>();
  const pending: [string, string][] = [];
  for (const header of HEADERS) {
    const source = stripComments(readFileSync(path.join(rathenaDir, header), 'utf8'));
    for (const match of source.matchAll(/^#define\s+([A-Za-z_]\w*)\s+([^\n]+)$/gm)) {
      pending.push([match[1] as string, (match[2] as string).trim()]);
    }
    for (const match of source.matchAll(/\benum\s+\w*\s*(?::\s*\w+\s*)?\{([^}]*)\}/g)) {
      // Members without a value follow the previous one; kept as "prev + 1" expressions.
      let previous: string | undefined;
      for (const raw of (match[1] as string).split(',')) {
        const member = raw.replace(/#\w+[^\n]*/g, '').trim();
        if (member === '') continue;
        const [name, value] = member.split('=').map((part) => part.trim()) as [string, string?];
        const expression = value ?? (previous === undefined ? '0' : `${previous} + 1`);
        pending.push([name, expression]);
        previous = name;
      }
    }
  }
  // Definitions may refer to names defined later, so resolve until nothing changes.
  let progress = true;
  while (progress) {
    progress = false;
    for (const [name, expression] of pending) {
      if (known.has(name)) continue;
      const value = evaluate(expression, known);
      if (value !== undefined) {
        known.set(name, value);
        progress = true;
      }
    }
  }
  return known;
}

function main(): void {
  const repoRoot = path.resolve(import.meta.dirname, '..', '..');
  const rathenaDir = resolveRathenaDir(process.argv.slice(2), process.env, repoRoot);
  const known = resolveHeaderValues(rathenaDir);
  const source = stripComments(
    readFileSync(path.join(rathenaDir, 'src/map/script_constants.hpp'), 'utf8'),
  );
  const values = new Map<string, number>();
  const bonuses = new Set<string>();
  const unresolved: string[] = [];
  const exportPattern =
    /export_(?:deprecated_)?constant(2?)\(\s*(?:"([^"]+)"\s*,\s*([^)]+)|([A-Za-z_]\w*))\s*\)/g;
  for (const match of source.matchAll(exportPattern)) {
    const name = (match[2] ?? match[4]) as string;
    const expression = (match[3] ?? match[4]) as string;
    if (/^b[A-Z]/.test(name) && /^SP_\w+$/.test(expression.trim())) {
      bonuses.add(name);
      continue;
    }
    if (!VALUE_PREFIXES.some((prefix) => name.toUpperCase().startsWith(prefix))) continue;
    const value = evaluate(expression.trim(), known);
    if (value === undefined) unresolved.push(`${name} = ${expression}`);
    else values.set(name, value);
  }
  if (unresolved.length > 0) {
    throw new Error(`Unresolved constants:\n  ${unresolved.join('\n  ')}`);
  }
  const commit = execFileSync('git', ['-C', rathenaDir, 'rev-parse', 'HEAD'], {
    encoding: 'utf8',
  }).trim();

  const lines = [
    '// Generated by extract-constants.ts from rAthena src/map/script_constants.hpp',
    `// at ${commit}. Do not edit by hand; rerun the extractor.`,
    '// Names are rAthena’s spelling; scripts may use any case.',
    '',
    '/** Script constants the parsed subset can use, by rAthena name. */',
    'export const SCRIPT_CONSTANTS: Readonly<Record<string, number>> = {',
    ...[...values].map(([name, value]) => `  ${name}: ${value},`),
    '};',
    '',
    '/** Every bonus name rAthena exports (`bStr`, `bAddRace`, ...). */',
    'export const BONUS_NAMES: readonly string[] = [',
    ...[...bonuses].map((name) => `  '${name}',`),
    '];',
    '',
  ];
  const outFile = path.join(import.meta.dirname, 'constants.ts');
  writeFileSync(outFile, lines.join('\n'));
  console.log(`wrote ${outFile}: ${values.size} constants, ${bonuses.size} bonus names`);
}

main();
