import type { Item, ScriptStmt } from '../src/data/types.ts';
import { parseScript } from './script/parser.ts';

export const COVERAGE_FILE = 'docs/script-coverage.md';

function percent(part: number, whole: number): string {
  return whole === 0 ? '–' : `${((100 * part) / whole).toFixed(1)} %`;
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/`/g, "'");
}

function collectBonusNames(statements: readonly ScriptStmt[], into: Set<string>): void {
  for (const statement of statements) {
    if (statement.k === 'bonus') into.add(statement.name);
    else if (statement.k === 'if') {
      collectBonusNames(statement.then, into);
      collectBonusNames(statement.else, into);
    }
  }
}

/** Number of items whose parsed effects use each bonus name, most used first. */
export function bonusUsage(items: readonly Item[]): [string, number][] {
  const counts = new Map<string, number>();
  for (const item of items) {
    if (item.effects === null) continue;
    const names = new Set<string>();
    collectBonusNames(item.effects, names);
    for (const name of names) counts.set(name, (counts.get(name) ?? 0) + 1);
  }
  return [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
}

/**
 * The script coverage report: totals, the unsupported items grouped by
 * reason with the statement that stopped the parser, and bonus usage.
 */
export function coverageReport(
  items: readonly Item[],
  names: Readonly<Record<number, string>>,
  scripts: ReadonlyMap<number, string>,
): string {
  const scripted = items.filter((item) => (scripts.get(item.id) ?? '').trim() !== '');
  const unsupported = scripted.filter((item) => item.effects === null);
  const visible = scripted.filter((item) => item.hidden !== true);
  const visibleUnsupported = visible.filter((item) => item.effects === null);

  const byReason = new Map<string, Item[]>();
  for (const item of unsupported) {
    const reason = item.unsupported ?? 'unknown';
    byReason.set(reason, [...(byReason.get(reason) ?? []), item]);
  }
  const reasons = [...byReason].sort(
    (a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]),
  );

  const row = (label: string, all: number, failed: number) =>
    `| ${label} | ${all} | ${all - failed} | ${failed} | ${percent(all - failed, all)} |`;
  const lines = [
    '# Script coverage',
    '',
    'Generated by `pnpm data`; do not edit. Lists which equipment scripts the',
    'parser in `data-pipeline/script/` converts into effects. An unsupported',
    'script can be rewritten in `data-overrides/items.yml` (`Script:`).',
    '',
    '| Equipment with a script | Items | Parsed | Unsupported | Parsed |',
    '| --- | ---: | ---: | ---: | ---: |',
    row('All', scripted.length, unsupported.length),
    row('Not hidden', visible.length, visibleUnsupported.length),
    '',
    '## Unsupported by reason',
    '',
    '| Reason | Items |',
    '| --- | ---: |',
    ...reasons.map(([reason, list]) => `| ${cell(reason)} | ${list.length} |`),
  ];
  for (const [reason, list] of reasons) {
    lines.push('', `### ${cell(reason)}`, '', '| Id | Name | Hidden | Statement |');
    lines.push('| ---: | --- | --- | --- |');
    for (const item of list) {
      const result = parseScript(scripts.get(item.id) ?? '');
      const statement = result.ok ? '' : result.statement;
      const hidden = item.hidden === true ? 'yes' : '';
      lines.push(
        `| ${item.id} | ${cell(names[item.id] ?? item.aegisName)} | ${hidden} | \`${cell(statement)}\` |`,
      );
    }
  }
  lines.push('', '## Bonuses in parsed scripts', '', '| Bonus | Items |', '| --- | ---: |');
  for (const [name, count] of bonusUsage(items)) lines.push(`| \`${name}\` | ${count} |`);
  return `${lines.join('\n')}\n`;
}
